/**
 * Find a train from DB or dynamically generate train details for ANY 5-digit Indian train number.
 */
export function findOrGenerateTrain(queryOrNumber: string): Train {
  const cleanNumber = queryOrNumber.trim().replace(/\D/g, '');
  const existing = TRAINS_DB.find(
    (t) => t.number === cleanNumber || t.id === cleanNumber || t.name.toLowerCase().includes(queryOrNumber.toLowerCase())
  );
  if (existing) return existing;

  const num = cleanNumber || '12000';
  let type: Train['type'] = 'superfast';
  if (num.startsWith('120') || num.startsWith('220')) type = 'shatabdi';
  else if (num.startsWith('123') || num.startsWith('124') || num.startsWith('129') || num.startsWith('226')) type = 'rajdhani';
  else if (num.startsWith('206') || num.startsWith('224')) type = 'vande_bharat';
  else if (num.startsWith('122')) type = 'duronto';
  else if (num.startsWith('121') || num.startsWith('128')) type = 'mail';

  const firstDigit = num[0] || '1';
  const stationPairs = [
    { from: 'New Delhi', fromCode: 'NDLS', to: 'MGR Chennai Central', toCode: 'MAS', dist: 2182 },
    { from: 'KSR Bengaluru', fromCode: 'SBC', to: 'New Delhi', toCode: 'NDLS', dist: 2409 },
    { from: 'CSMT Mumbai', fromCode: 'CSMT', to: 'Howrah Junction', toCode: 'HWH', dist: 1968 },
    { from: 'Varanasi Junction', fromCode: 'BSB', to: 'New Delhi', toCode: 'NDLS', dist: 757 },
    { from: 'Ahmedabad Junction', fromCode: 'ADI', to: 'Mumbai Central', toCode: 'MMCT', dist: 493 },
    { from: 'Jaipur Junction', fromCode: 'JP', to: 'New Delhi', toCode: 'NDLS', dist: 308 },
    { from: 'Patna Junction', fromCode: 'PNBE', to: 'Howrah Junction', toCode: 'HWH', dist: 532 },
  ];
  const pair = stationPairs[parseInt(num) % stationPairs.length];

  return {
    id: num,
    number: num,
    name: `Express Train (${num})`,
    type,
    from: pair.from,
    to: pair.to,
    fromCode: pair.fromCode,
    toCode: pair.toCode,
    departureTime: '08:00',
    arrivalTime: '20:30',
    daysOfOperation: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
    distance: pair.dist,
  };
}
